function container({ addComponents, theme }) {
  addComponents({
    ".container": {
      width: theme("width.full"),
      margin: `0 ${theme("margin.auto")}`,
      maxWidth: theme("maxWidth.full"),
      "@screen md": { maxWidth: "960px" },
      "@screen lg": { maxWidth: "1376px" },
    },
  });
}

